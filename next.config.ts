import type { NextConfig } from "next";

/*
 * Сайт на телефоне во время разработки.
 * Телефон открывает сайт по адресу компьютера в домашней сети, например
 * 192.168.1.5:3000. Сервер разработки Next.js по умолчанию принимает
 * служебные запросы только с localhost, а с другого адреса отказывает: без
 * них страница на телефоне не оживает, и ни одна кнопка не работает.
 * Здесь разрешены все адреса домашних и офисных сетей: 10.x.x.x,
 * 172.16.x.x до 172.31.x.x и 192.168.x.x. На собранный сайт это не влияет,
 * настройка действует только в режиме разработки.
 */
const homeNetworks = [
  "10.*.*.*",
  "192.168.*.*",
  ...Array.from({ length: 16 }, (_, i) => `172.${16 + i}.*.*`),
];

/*
 * Фотографии объектов лежат на бэкенде (BACKEND_URL из .env.local, по
 * умолчанию http://localhost:8000) по адресам /media/... Сайт отдаёт их со
 * своего адреса: запрос /media/... к сайту уходит на бэкенд (rewrites ниже),
 * а lib/api.ts (mediaSrc) оставляет в адресах фото только путь. Поэтому
 * посетитель к бэкенду не обращается, и на хостинге бэкенд можно закрыть
 * снаружи. Список remotePatterns остаётся на случай полного адреса картинки
 * не с /media: next/image берёт картинки с чужого адреса только из него.
 * localhost и 127.0.0.1 на порту 8000 разрешены всегда, потому что бэкенд
 * локально отвечает по обоим.
 */
const backend = new URL(process.env.BACKEND_URL ?? "http://localhost:8000");
const backendHosts = Array.from(
  new Set([backend.hostname, "localhost", "127.0.0.1"]),
).map((hostname) => ({
  protocol: backend.protocol.replace(":", "") as "http" | "https",
  hostname,
  port: backend.port,
  pathname: "/media/**",
}));

/*
 * Пока бэкенд локальный (localhost, 127.0.0.1, домашняя сеть), next/image
 * нужно отдельно разрешить брать картинки с локальных адресов: по умолчанию
 * он их не берёт. На хостинге у бэкенда будет обычный адрес, и это не нужно.
 */
const backendIsLocal =
  /^(localhost|127\.\d+\.\d+\.\d+|10\.\d+\.\d+\.\d+|192\.168\.\d+\.\d+|172\.(1[6-9]|2\d|3[01])\.\d+\.\d+)$/.test(
    backend.hostname,
  );

/*
 * Страницы с данными из бэкенда (списки, апартамент, ресторан) собираются
 * сервером при каждом запросе, остальные при сборке. Режим cacheComponents
 * из заготовки выключен 15.10: с ним переход по ссылке показывал пустую
 * страницу на полсекунды, пока подгружались данные.
 */
const nextConfig: NextConfig = {
  allowedDevOrigins: homeNetworks,
  /*
   * Кружок «N» с числом ошибок внизу слева в режиме разработки скрыт, чтобы
   * не мешал смотреть дизайн (Анна, 15.10). На собранном сайте его нет и так.
   * Ошибки, из-за которых страница не работает, Next всё равно покажет окном.
   */
  devIndicators: false,
  images: {
    remotePatterns: backendHosts,
    dangerouslyAllowLocalIP: backendIsLocal,
  },
  /*
   * Фото с бэкенда под адресом сайта: /media/... сайт сам запрашивает у
   * бэкенда по BACKEND_URL и отдаёт посетителю. Адрес бэкенда подставляется
   * при сборке, поэтому после его смены сайт пересобрать.
   */
  async rewrites() {
    return [
      {
        source: "/media/:path*",
        destination: `${backend.origin}/media/:path*`,
      },
    ];
  },
  turbopack: {
    rules: {
      "*.css": {
        loaders: ["@tailwindcss/turbopack"],
        as: "*.css",
      },
    },
  },
};

export default nextConfig;
